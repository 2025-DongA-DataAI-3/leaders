def _match(text: str) -> Optional[str]:
    text = text.lower()
    for type_key, keywords in _TYPE_KEYWORD_RULES:
        for kw in keywords:
            if kw.lower() in text:
                return type_key
    return None


def classify_section_type(label: str, sub: Optional[str] = "", placeholder: Optional[str] = "") -> str:
    """
    섹션의 label/sub/placeholder 텍스트를 보고 가장 그럴듯한 항목 유형 key를 반환한다.

    신뢰도 우선순위: label > sub > placeholder.
    label은 양식 설계자가 붙인 공식 항목명이라 신호가 명확하고,
    placeholder는 GPT가 생성한 자유 서술이라 "시장", "전략" 같은 범용 단어가
    섞여 들어가 오매칭을 일으키기 쉽다. 따라서 label에서 먼저 매칭을 시도하고,
    실패할 때만 sub, placeholder로 순차 폴백한다.
    매칭되는 게 없으면 "default"를 반환한다.
    """
    for text in (label or "", sub or "", placeholder or ""):
        if not text:
            continue
        matched = _match(text)
        if matched:
            return matched
    return "default"


def get_guide_for_section(label: str, sub: Optional[str] = "", placeholder: Optional[str] = "") -> SectionTypeGuide:
    type_key = classify_section_type(label, sub, placeholder)
    return SECTION_TYPE_GUIDES[type_key]